// One full cycle: logo -> draw -> hold -> back to logo. A 7-letter word
// drawing convincingly needs at least ~1.5-2s on its own, so anything
// tighter than ~6s starts to feel rushed rather than "written"; much past
// ~9-10s and the loop reads as slow/forgotten. ~7.7s lands in the middle.
const LOGO_HOLD = 2.5; // seconds the static icon stays put
const CROSSFADE = 0.35; // icon <-> wordmark fade
const DRAW_DURATION = 1.1; // seconds each letter's outline takes to draw
const DRAW_STAGGER = 0.11; // gap between one letter starting and the next
const FILL_IN = 0.35; // outline -> solid fill, once fully drawn
const TEXT_HOLD = 2.2; // seconds the finished wordmark stays put

const prefersReducedMotion = () =>
  typeof window !== "undefined" &&
  !!window.matchMedia &&
  window.matchMedia("(prefers-reduced-motion: reduce)").matches;

export default function CrackerMark() {
  const logoRef = useRef(null);
  const wordmarkRef = useRef(null);
  const pathRefs = useRef([]);

  useEffect(() => {
    const logo = logoRef.current;
    const wordmark = wordmarkRef.current;
    const paths = pathRefs.current.filter(Boolean);
    if (!logo || !wordmark || paths.length !== WORDMARK_PATHS.length) return;

    // Real per-letter lengths, measured once — a guessed dasharray either
    // leaves a gap before the line starts or clips its end.
    const lengths = paths.map((p) => p.getTotalLength());

    gsap.set(logo, { opacity: 1 });
    gsap.set(wordmark, { opacity: 0 });
    gsap.set(paths, { fill: "transparent", stroke: "black", strokeWidth: 1 });
    paths.forEach((p, i) => {
      gsap.set(p, { strokeDasharray: lengths[i], strokeDashoffset: lengths[i] });
    });

    if (prefersReducedMotion()) {
      // The static icon alone is the reduced-motion state — no draw loop.
      return;
    }

    const tl = gsap.timeline({ repeat: -1 });

    tl.to(logo, { opacity: 0, duration: CROSSFADE, delay: LOGO_HOLD })
      .set(wordmark, { opacity: 1 }, "<")
      .to(paths, {
        strokeDashoffset: 0,
        duration: DRAW_DURATION,
        ease: "power2.inOut",
        stagger: DRAW_STAGGER,
      })
      .to(paths, { fill: "black", stroke: "transparent", duration: FILL_IN })
      .to(wordmark, { opacity: 0, duration: CROSSFADE, delay: TEXT_HOLD })
      .set(paths, { fill: "transparent", stroke: "black" })
      .set(paths, { strokeDashoffset: (i) => lengths[i] })
      .to(logo, { opacity: 1, duration: CROSSFADE }, "<");

    return () => {
      tl.kill();
    };
  }, []);

  return (
    <div className="crackerMark">
      <img ref={logoRef} className="crackerMark__logo" src={MainLogo} alt="Cracker" />
      <svg
        ref={wordmarkRef}
        className="crackerMark__wordmark"
        viewBox="0 0 85 19"
        fill="none"
        xmlns="http://www.w3.org/2000/svg"
        aria-hidden="true"
      >
        {WORDMARK_PATHS.map((d, i) => (
          <path key={i} ref={(el) => (pathRefs.current[i] = el)} d={d} />
        ))}
      </svg>
    </div>
  );
}
